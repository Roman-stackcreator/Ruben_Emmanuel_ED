 /*
Programa que guarda 100000 objetos en un arreglo  
  */


public class Arrays {
    public static void main(String[] args) {
        int[] arreglo = new int[1000000];
        for(int i=0 ;i<100000;i++){
            arreglo[i]=i;
        }

    }   
}
